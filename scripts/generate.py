"""Generates gridoverture._generated from the two files in spec/: the SDK's low-level client and
the API contract it implements (the spec's info.version), from the platform's
openapi.public.json, and the CGMES 3.0 class hierarchy, from cgmes-3.0-class-parents.json.

openapi.public.json holds the platform's public routes only, the ones its gateway lets through, so
the SDK cannot call a route its users cannot reach. It is vendored at the platform version that
spec/PLATFORM_REF names, and scripts/sync_openapi.py replaces it. The hierarchy lets
Version.find("EnergyConsumer") find a NonConformLoad. Neither output is edited by hand: a test
fails when the committed files differ from what this script makes.

Usage: generate.py [output_directory]

The output replaces src/gridoverture/_generated unless another directory is given, which is how the
test compares a fresh generation with the committed files without rewriting them.
"""

import json
import pathlib
import shutil
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parents[1]
SPEC = ROOT / "spec"
OPENAPI = SPEC / "openapi.public.json"
CLASS_PARENTS = SPEC / "cgmes-3.0-class-parents.json"
OUT = ROOT / "src" / "gridoverture" / "_generated"
# No post hooks: formatting with whatever ruff is on the PATH would make the output depend on the
# machine. The generator's version is pinned in the dev dependencies.
CONFIG = "post_hooks: []\n"
HIERARCHY = '''"""
Each CGMES 3.0 class and the class it specializes, as ENTSO-E's RDFS vocabularies declare them.
Generated by scripts/generate.py from spec/cgmes-3.0-class-parents.json; not edited by hand.
"""

PARENTS = {
%s}
'''
CONTRACT_MODULE = '''"""
The version of the platform's API contract this client was generated from: the info.version of
spec/openapi.public.json. Generated by scripts/generate.py; not edited by hand.
"""

CONTRACT = %s
'''


def hierarchy() -> str:
    """The module that holds the CGMES 3.0 class hierarchy."""
    parents = json.loads(CLASS_PARENTS.read_text(encoding="utf-8"))["parents"]
    lines = [
        f"    {json.dumps(name)}: {json.dumps(parent)},\n"
        for name, parent in sorted(parents.items())
    ]
    return HIERARCHY % "".join(lines)


def generate(output_directory: pathlib.Path) -> None:
    """Write the client into `output_directory`, replacing whatever it held."""
    generator = shutil.which("openapi-python-client")
    if generator is None:
        raise FileNotFoundError("openapi-python-client is not installed: run uv sync")
    with tempfile.TemporaryDirectory() as scratch:
        config = pathlib.Path(scratch) / "config.yaml"
        config.write_text(CONFIG, encoding="utf-8")
        target = pathlib.Path(scratch) / "client"
        subprocess.run(
            [
                generator,
                "generate",
                "--path",
                str(OPENAPI),
                "--output-path",
                str(target),
                "--meta",
                "none",
                "--config",
                str(config),
            ],
            check=True,
            capture_output=True,
            text=True,
        )
        (target / "cim_classes.py").write_text(hierarchy(), encoding="utf-8", newline="\n")
        version = json.loads(OPENAPI.read_text(encoding="utf-8"))["info"]["version"]
        (target / "contract.py").write_text(
            CONTRACT_MODULE % json.dumps(version), encoding="utf-8", newline="\n"
        )
        shutil.rmtree(output_directory, ignore_errors=True)
        shutil.copytree(target, output_directory)


if __name__ == "__main__":
    output = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else OUT
    generate(output)
    print(f"written: {output}")
